    // 3x5 digits, drawn at double size for the minutes-left view
    private static final String[] DIGITS = {
        "###/#.#/#.#/#.#/###", "..#/..#/..#/..#/..#", "###/..#/###/#../###",
        "###/..#/###/..#/###", "#.#/#.#/###/..#/..#", "###/#../###/..#/###",
        "###/#../###/#.#/###", "###/..#/..#/..#/..#", "###/#.#/###/#.#/###",
        "###/#.#/###/..#/###",
    };
    private static final String QUESTION = "###/..#/.##/.../.#.";

    private Glyphs() {}

    /** Lit dots for a planet's symbol, row by row. */
    static boolean[] planet(String planet) {
        boolean[] dots = new boolean[SIZE * SIZE];
        String[] rows = PLANETS.get(planet);
        if (rows == null) return question();
        for (int y = 0; y < SIZE; y++)
            for (int x = 0; x < SIZE; x++)
                dots[y * SIZE + x] = rows[y].charAt(x) == '#';
        return dots;
    }

    /** A number from 0 to 999 centred on the matrix. */
    static boolean[] number(int value) {
        String text = String.valueOf(Math.max(0, Math.min(999, value)));
        boolean[] dots = new boolean[SIZE * SIZE];
        int width = text.length() * 6 + (text.length() - 1) * 2;
        int left = (SIZE - width) / 2;
        for (int i = 0; i < text.length(); i++)
            stamp(dots, DIGITS[text.charAt(i) - '0'], left + i * 8, 7);
        return dots;
    }

    /** Shown when no location has been saved yet. */
    static boolean[] question() {
        boolean[] dots = new boolean[SIZE * SIZE];
        stamp(dots, QUESTION, 9, 7);
        return dots;
    }

    private static void stamp(boolean[] dots, String pattern, int left, int top) {
        String[] rows = pattern.split("/");
        for (int y = 0; y < rows.length; y++)
            for (int x = 0; x < rows[y].length(); x++)
                if (rows[y].charAt(x) == '#')
                    for (int dy = 0; dy < 2; dy++)
                        for (int dx = 0; dx < 2; dx++)
                            dots[(top + y * 2 + dy) * SIZE + left + x * 2 + dx] = true;
    }
